#!/usr/bin/env python3
"""Generate src/unicode_tables.h: code point ranges for \\p{L} and \\p{N}.

The BPE pre-tokenizer regex needs Unicode general categories; rather than link
ICU we bake the two categories it uses into sorted range tables.
"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    lines = [f"static const uint32_t {name}[][2] = {{"]
    row = []
    for a, b in rs:
        row.append(f"{{0x{a:X},0x{b:X}}}")
        if len(row) == 6:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    letters = ranges(lambda c: unicodedata.category(c).startswith("L"))
    numbers = ranges(lambda c: unicodedata.category(c).startswith("N"))
    print(f"// Generated by tools/gen_unicode.py (Unicode {unicodedata.unidata_version}). Do not edit.")
    print("#pragma once\n#include <cstdint>\n")
    print(emit("kUnicodeLetterRanges", letters))
    print()
    print(emit("kUnicodeNumberRanges", numbers))


if __name__ == "__main__":
    sys.exit(main())
